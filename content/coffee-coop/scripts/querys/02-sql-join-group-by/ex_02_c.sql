-- Deliveries of 2026-09-30 with analysis code and cup score (including unanalyzed)

SELECT
    T1.delivery_id AS delivery,
    T2.analysis_id AS analysis,
    T2.cup_score AS cup_score
FROM 
    buy.deliveries AS T1
LEFT JOIN buy.quality_analyses AS T2
    ON T1.delivery_id = T2.delivery_id
WHERE 
    T1.delivery_id LIKE 'DLV-20260930-%'
ORDER BY 
    T1.delivery_id ASC;

